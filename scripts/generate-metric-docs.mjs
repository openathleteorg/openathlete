#!/usr/bin/env node
// Writes the public page on the science behind the statistics from the metric
// registry, so it can never say something else than the app:
//   pnpm shared build && node scripts/generate-metric-docs.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const { METRIC_REGISTRY } = require("../libs/shared/dist/index.cjs");
const messages = JSON.parse(readFileSync("apps/web/messages/en.json", "utf8"));

// Message keys of the metrics, where they differ from the registry key
const COPY = {
  sessionRpe: ["metric_srpe_name", "srpe"],
  trimp: ["metric_trimp_name", "trimp"],
  ctl: ["fitness_ctl", "ctl"],
  atl: ["fatigue_atl", "atl"],
  tsb: ["tsb_balance", "tsb"],
  intensityDistribution: ["statistics_section_intensity", "intensity"],
  efficiency: ["statistics_efficiency", "efficiency"],
  decoupling: ["statistics_decoupling", "decoupling"],
  monotony: ["statistics_monotony", "monotony"],
  longRun: ["statistics_long_runs", "long_run"],
  cardiacCost: ["statistics_cost_title", "cost"],
  drift: ["statistics_durability_title", "drift"],
  recordCoherence: ["statistics_coherence_title", "coherence"],
  racePrediction: ["statistics_predictions_title", "prediction"],
  hrvTrend: ["statistics_recovery_hrv", "hrv"],
  criticalSpeed: ["statistics_critical_speed", "critical_speed"],
  criticalSwimSpeed: ["statistics_critical_swim", "critical_swim"],
  criticalPower: ["statistics_critical_power", "critical_power"],
  gap: ["gap", "gap"],
};

const VERDICTS = {
  validated: "Validated",
  reserved: "Validated, with limits",
  estimate: "Estimate",
};

const sections = Object.entries(METRIC_REGISTRY).map(([key, metric]) => {
  const [name, stem] = COPY[key];
  const sources = metric.sources
    .map(({ label, url }) => `[${label}](${url})`)
    .join(", ");
  return [
    `## ${messages[name]}`,
    "",
    `**${VERDICTS[metric.verdict]}.** ${messages[`metric_${stem}_what`]}`,
    "",
    "```text",
    metric.formula,
    "```",
    "",
    `**Limits:** ${messages[`metric_${stem}_limits`]}`,
    "",
    `**Sources:** ${sources}`,
  ].join("\n");
});

writeFileSync(
  "apps/docs/content/docs/guides/statistics-science.mdx",
  `---
title: The science behind the statistics
description: What each derived figure is, how it is computed, and how far to trust it.
---

{/* Generated by scripts/generate-metric-docs.mjs: change the registry instead */}

Raw figures (time, distance, heart rate) are shown as recorded. Every figure
derived from them has an entry here, and a figure without one is not shown.
Ratios without support, such as the acute:chronic workload ratio, are left out
on purpose.

- **Validated**: backed by the literature.
- **Validated, with limits**: backed by the literature, within the limits given.
- **Estimate**: useful but without solid validation, always labelled in the app.

${sections.join("\n\n")}
`,
);
