/**
 * Zod Schemas for Training Plan Generation
 *
 * These schemas define the data structures used throughout the plan generation workflow.
 * All agents and workflow steps use these schemas for type safety and validation.
 *
 * Data Flow:
 * AthleteFacts → MacroPlan → MesoBlocks → WeekIntentions → ScheduledWeeks → ValidationReport
 */
import { z } from 'zod';

// ============================================================================
// ATHLETE FACTS
// ============================================================================

/**
 * Comprehensive athlete profile data used for plan generation
 * Generated by: athlete-profile.agent
 * Used by: All planning agents
 */
export const athleteFactsSchema = z.object({
  // Basic profile
  athleteId: z.number(),
  name: z.string().nullish(),
  email: z.string().nullish(),

  // Current fitness baseline
  currentFitness: z.object({
    recentWeeklyVolume: z
      .number()
      .describe('Average weekly volume in seconds over last 4 weeks'),
    recentWeeklyDistance: z
      .number()
      .describe('Average weekly distance in meters'),
    longestRecentRun: z
      .number()
      .describe('Longest run in last 8 weeks (meters)'),
    currentLoad: z.object({
      weeklyTrimp: z.number().describe('Current weekly TRIMP'),
      acuteChronicRatio: z.number().describe('Acute:Chronic workload ratio'),
    }),
  }),

  // Availability
  availability: z.array(
    z.object({
      dayOfWeek: z.number().describe('0=Sunday, 1=Monday, ..., 6=Saturday'),
      startTime: z.string().describe('HH:mm format'),
      endTime: z.string().describe('HH:mm format'),
      priority: z.enum(['LOW', 'MEDIUM', 'HIGH']),
    }),
  ),

  // Constraints
  constraints: z.object({
    maxWeeklyVolume: z
      .number()
      .nullish()
      .describe('Maximum weekly volume in seconds'),
    preferredRestDays: z
      .array(z.number())
      .nullish()
      .describe('Preferred rest days (0-6)'),
    avoidDays: z
      .array(z.number())
      .nullish()
      .describe('Days to avoid training (0-6)'),
    injuries: z
      .array(z.string())
      .nullish()
      .describe('Current or recent injuries'),
  }),

  // Experience & preferences
  experienceLevel: z
    .enum(['BEGINNER', 'INTERMEDIATE', 'ADVANCED', 'ELITE'])
    .nullish(),
  trainingHistory: z
    .string()
    .nullish()
    .describe('Narrative summary of training background'),
});

export type AthleteFacts = z.infer<typeof athleteFactsSchema>;

