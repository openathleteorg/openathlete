/**
 * Specific session plans for a week (before scheduling)
 * Generated by: micro-plan.agent
 * Used by: scheduling.agent
 */
export const sessionIntentionSchema = z.object({
  sessionId: z.string().nullish().describe('Unique identifier for tracking'),
  type: z
    .enum([
      'INTERVAL',
      'LONG_RUN',
      'TEMPO',
      'EASY',
      'RECOVERY',
      'STRENGTH',
      'RACE',
    ])
    .describe('Session type'),
  sport: z.enum(['RUNNING', 'CYCLING', 'SWIMMING', 'STRENGTH', 'OTHER']),
  targetDuration: z.number().describe('Target duration in seconds'),
  targetDistance: z.number().nullish().describe('Target distance in meters'),
  targetElevationGain: z
    .number()
    .nullish()
    .describe('Target elevation gain in meters'),
  targetIntensity: z
    .object({
      zone: z.string().nullish().describe('Training zone (Z1, Z2, Z3, Z4, Z5)'),
      rpe: z.number().min(0).max(1).describe('RPE on 0-1 scale'),
    })
    .describe('Target intensity metrics'),
  description: z.string().describe('Detailed session description'),
  structure: z
    .any()
    .nullish()
    .describe('Structured workout definition (if applicable)'),
  dayOfWeek: z
    .number()
    .nullish()
    .describe('Preferred day (0-6), null if not yet scheduled'),
  priority: z
    .enum(['HIGH', 'MEDIUM', 'LOW'])
    .describe('Session priority for scheduling'),
});

export const weekIntentionsSchema = z.object({
  weekNumber: z.number(),
  startDate: z.string(),
  endDate: z.string(),
  theme: z.string(),
  targetVolume: z.number(),
  sessions: z.array(sessionIntentionSchema),
});

export type WeekIntentions = z.infer<typeof weekIntentionsSchema>;
export type SessionIntention = z.infer<typeof sessionIntentionSchema>;

