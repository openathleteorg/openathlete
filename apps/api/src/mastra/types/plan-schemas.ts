/**
 * Sessions assigned to specific calendar days/times
 * Generated by: scheduling.agent
 * Used by: qa.agent, save-plan.tool
 */
export const scheduledSessionSchema = sessionIntentionSchema.extend({
  scheduledDate: z.string().describe('ISO datetime when session is scheduled'),
  scheduledTime: z.string().nullish().describe('Start time in HH:mm format'),
  availabilitySlotId: z
    .number()
    .nullish()
    .describe('ID of the availability slot used'),
});

export const scheduledWeekSchema = z.object({
  weekNumber: z.number(),
  startDate: z.string(),
  endDate: z.string(),
  theme: z.string(),
  targetVolume: z.number(),
  sessions: z.array(scheduledSessionSchema),
  schedulingWarnings: z
    .array(z.string())
    .nullish()
    .describe('Warnings about scheduling compromises or near-violations'),
  unscheduledSessions: z
    .array(sessionIntentionSchema)
    .nullish()
    .describe('Sessions that could not be placed'),
  schedulingNotes: z
    .string()
    .nullish()
    .describe('Overall explanation of scheduling strategy'),
});

export type ScheduledWeek = z.infer<typeof scheduledWeekSchema>;
export type ScheduledSession = z.infer<typeof scheduledSessionSchema>;

