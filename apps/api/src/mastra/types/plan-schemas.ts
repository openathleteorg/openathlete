/**
 * Convert MacroPlan phases to cycle structure for database
 */
export function macroPlanToCycles(
  macroPlan: MacroPlan,
  scheduledWeeks: ScheduledWeek[],
) {
  return macroPlan.phases.map((phase) => {
    // Find weeks that belong to this phase
    const phaseStartDate = new Date(phase.startDate);
    const phaseEndDate = new Date(phase.endDate);

    const phaseWeeks = scheduledWeeks.filter((week) => {
      const weekStart = new Date(week.startDate);
      return weekStart >= phaseStartDate && weekStart < phaseEndDate;
    });

    return {
      name: phase.name,
      phase: phase.phase,
      startDate: phase.startDate,
      endDate: phase.endDate,
      weeks: phaseWeeks,
    };
  });
}

/**
 * Generate a plan name from goal
 */
export function generatePlanName(goal: {
  raceName: string;
  raceDate: string;
}): string {
  const raceDate = new Date(goal.raceDate);
  const month = raceDate.toLocaleString('en-US', { month: 'long' });
  const year = raceDate.getFullYear();
  return `${goal.raceName} - ${month} ${year}`;
}
