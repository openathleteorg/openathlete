/**
 * High-level training plan structure with phases
 * Generated by: macro-plan.agent
 * Used by: meso-plan.agent
 */
export const macroPlanPhaseSchema = z.object({
  name: z.string().describe('Phase name, e.g., "Base Building Phase 1"'),
  phase: z.enum(['BASE', 'SPECIFIC', 'TAPER', 'RECOVERY', 'COMPETITION']),
  startDate: z.string().describe('ISO date string'),
  endDate: z.string().describe('ISO date string'),
  durationWeeks: z.number().describe('Number of weeks in this phase'),
  targetWeeklyVolume: z
    .object({
      min: z.number().describe('Minimum weekly volume in seconds'),
      max: z.number().describe('Maximum weekly volume in seconds'),
    })
    .describe('Target volume range for this phase'),
  volumeProgression: z
    .enum(['LINEAR', 'STEPPED', 'UNDULATING'])
    .describe('How volume progresses within phase'),
  focus: z.string().describe('Main training focus for this phase'),
  keyWorkouts: z
    .array(z.string())
    .describe('Types of key workouts in this phase'),
});

export const macroPlanMilestoneSchema = z.object({
  date: z.string().describe('ISO date string'),
  type: z.enum(['TEST', 'RACE', 'CHECKPOINT']),
  name: z.string().describe('Milestone name'),
  description: z.string().describe('Details about this milestone'),
});

export const macroPlanSchema = z.object({
  totalDurationWeeks: z.number().describe('Total plan duration in weeks'),
  phases: z.array(macroPlanPhaseSchema),
  milestones: z.array(macroPlanMilestoneSchema),
  overallStrategy: z
    .string()
    .describe('Narrative description of the macro plan strategy'),
  progressionRationale: z
    .string()
    .describe('Explanation of why this progression was chosen'),
});

export type MacroPlan = z.infer<typeof macroPlanSchema>;
export type MacroPlanPhase = z.infer<typeof macroPlanPhaseSchema>;
export type MacroPlanMilestone = z.infer<typeof macroPlanMilestoneSchema>;

