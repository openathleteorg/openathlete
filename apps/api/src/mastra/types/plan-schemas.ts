/**
 * Weekly training blocks within a phase
 * Generated by: meso-plan.agent
 * Used by: micro-plan.agent
 */
export const mesoWeekSchema = z.object({
  weekNumber: z
    .number()
    .describe('Week number within the entire plan (1, 2, 3, ...)'),
  startDate: z.string().describe('ISO date string'),
  endDate: z.string().describe('ISO date string'),
  theme: z
    .string()
    .describe('Week theme, e.g., "VO2max intervals", "Base building"'),
  targetVolume: z.number().describe('Target weekly volume in seconds'),
  targetLoad: z.number().nullish().describe('Target training load (TRIMP)'),
  intensityFocus: z
    .enum(['EASY', 'MODERATE', 'HARD', 'MIXED'])
    .describe('Primary intensity focus for the week'),
  isRecoveryWeek: z.boolean().describe('Whether this is a recovery week'),
});

export const mesoBlockSchema = z.object({
  blockNumber: z.number().describe('Block number within the phase'),
  phaseName: z.string().describe('Name of the parent phase'),
  weeks: z.array(mesoWeekSchema),
  blockTheme: z.string().describe('Overall theme for this 3-4 week block'),
  progressionPattern: z
    .string()
    .describe('How the block progresses (e.g., "3 weeks build + 1 recovery")'),
});

export type MesoBlock = z.infer<typeof mesoBlockSchema>;
export type MesoWeek = z.infer<typeof mesoWeekSchema>;

